package com.aura.meeting.model;

public class ReportingMetrics {
    private int total;

    private int pendentes;

    private int emAnalise;

    private int resolvidos;

    public int getTotal() {
        return total;
    }

    public void setTotal(int total) {
        this.total = total;
    }

    public int getPendentes() {
        return pendentes;
    }

    public void setPendentes(int pendentes) {
        this.pendentes = pendentes;
    }

    public int getEmAnalise() {
        return emAnalise;
    }

    public void setEmAnalise(int emAnalise) {
        this.emAnalise = emAnalise;
    }

    public int getResolvidos() {
        return resolvidos;
    }

    public void setResolvidos(int resolvidos) {
        this.resolvidos = resolvidos;
    }
}
